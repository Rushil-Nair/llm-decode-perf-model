@pytest.mark.parametrize("gpu", GPUS)
def test_fit_recovers_overhead_and_efficiency(calibs, gpu):
    cal = calibs[gpu]
    assert set(cal.curves) == {"gemm|bf16", "attn_decode|bf16", "attn_prefill|bf16", "rmsnorm|bf16"}
    for key, c in cal.curves.items():
        assert c.t0_source == "probe"
        assert c.t0_s * 1e6 == pytest.approx(gen.T0_US[c.op], rel=0.01)
        assert all(0 < e <= 1 for e in c.effs)
        assert c.n_clipped == 0 and c.n_faster_than_sol == 0
    checked = 0
    for r in main_records(gpu):
        c = cal.curves[f"{r['op']}|bf16"]
        # Efficiency is only identifiable when the work term matters: for e.g. a 1-token
        # RMSNorm (SOL 5 ns vs t0 2.5 us) a 2 ns error in t0 moves eff by 5% but the
        # predicted time by < 0.1% (reproduction is tested separately for every shape).
        if r["us"] - gen.T0_US[r["op"]] < 0.1 * r["us"]:
            continue
        checked += 1
        x = r["flops"] / r["bytes"] if c.feature == "ai" else r[c.feature]
        truth = gen.true_eff(r["op"], r["flops"], r["bytes"], r["shape"].get("weight_bytes"))
        assert c.eff(x, r["shape"].get("weight_bytes")) == pytest.approx(truth, rel=0.02), r["shape"]
    assert checked > 140  # nearly all of the 152 shapes


