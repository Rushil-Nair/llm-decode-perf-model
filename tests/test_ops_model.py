def test_gemm_shape_curves_and_pooled_fallback(calibs):
    cal, h = calibs["h100_sxm"], HW["h100_sxm"]
    cost = OpCostModel(h, cal, "empirical")
    # measured shape (k_proj, 8 MB: carries the synthetic small-shape penalty) -> its own curve
    k_op = Op("k", 2.0 * 16 * 4096 * 1024, weight_bytes=4096 * 1024 * 2,
              act_bytes=16 * (4096 + 1024) * 2, kind="gemm")
    d = cost.explain(k_op)
    assert d["source"] == "measured/shape"
    assert d["eff"] == pytest.approx(gen.true_eff("gemm", k_op.flops, k_op.bytes, k_op.weight_bytes), rel=0.01)
    # unmeasured shape (4096 x 8192, 64 MB) -> pooled curve, close to the unpenalised truth
    M, K, N = 16, 4096, 8192
    u = Op("u", 2.0 * M * K * N, weight_bytes=K * N * 2, act_bytes=M * (K + N) * 2, kind="gemm")
    d = cost.explain(u)
    assert d["source"] == "measured/pooled"
    truth_us = gen.true_us("gemm", u.flops, u.bytes, h, u.weight_bytes)
    assert d["time_s"] * 1e6 == pytest.approx(truth_us, rel=0.03)


def test_interpolation_is_shape_preserving_and_flat_outside():
    c = EfficiencyCurve(op="x", dtype="bf16", feature="bytes", xs=[1e3, 1e6, 1e9],
                        effs=[0.2, 0.8, 0.6])
    assert c.eff(1.0) == 0.2 and c.eff(1e12) == 0.6            # flat extrapolation
    assert c.eff(math.sqrt(1e3 * 1e6)) == pytest.approx(0.5)   # midpoint in log space
    grid = [10 ** (3 + 3 * i / 50) for i in range(51)]
    vals = [c.eff(v) for v in grid]
    assert all(b >= a for a, b in zip(vals, vals[1:]))          # monotone between knots
    assert max(c.eff(10 ** (6 + 3 * i / 50)) for i in range(51)) <= 0.8  # no overshoot


def test_without_probes_t0_is_min_excess_and_still_exact():
    h = HW["h100_sxm"]
    recs = [r for r in records("h100_sxm") if not r["shape"].get("probe")]
    cal = fit_calibration(recs, h)
    cost = OpCostModel(h, cal, "empirical")
    for c in cal.curves.values():
        assert c.t0_source == "min_excess"
        assert c.t0_s * 1e6 >= gen.T0_US[c.op] - 1e-9   # an upper bound on the true overhead
        assert all(0 < e <= 1 for e in c.effs)
    for r in keep_fastest(recs):
        assert predict_record(cost, r) * 1e6 == pytest.approx(r["us"], rel=0.02)


def test_faster_than_sol_is_clipped_and_counted():
    h = HW["rtx5090"]
    recs = []
    for M in (1, 64, 4096):
        fl, nb = bench.gemm_cost(M, 4096, 4096)
        recs.append({"op": "gemm", "dtype": "bf16", "shape": {"M": M, "K": 4096, "N": 4096},
                     "us": 1e6 * sol_time(fl, nb, h) * (0.9 if M == 4096 else 1.5),
                     "flops": fl, "bytes": nb})
    c = fit_calibration(recs, h).curves["gemm|bf16"]
    assert c.t0_s == 0.0 and c.t0_source == "min_excess"     # min(t - SOL) < 0 -> 0
    assert c.n_faster_than_sol == 1 and c.n_clipped == 1
    assert max(c.effs) == 1.0 and min(c.effs) > 0


