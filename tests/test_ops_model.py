def test_fit_calib_cli(tmp_path):
    d = tmp_path / "data" / "h100_sxm"
    d.mkdir(parents=True)
    shutil.copy(FIX / "synthetic_ops_h100_sxm.jsonl", d / "ops.jsonl")
