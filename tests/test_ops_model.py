    md = (res / "h100_sxm_ops_sol.md").read_text()
    assert "% of SOL" in md and "| gemm |" in md and "max |err| 0.00%" in md
    # unknown device / missing data: clean non-zero exit, no traceback
    assert fit_cli.main(["--data", str(tmp_path / "data" / "nope"), "--results", str(res)]) == 2
    assert fit_cli.main(["--data", str(d), "--hw", "h100_pcie", "--ops", str(tmp_path / "missing.jsonl"),
                         "--results", str(res)]) == 2
