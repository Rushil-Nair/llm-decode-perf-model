def test_op_family_mapping_proxies_and_fallbacks(calibs):
    cost = OpCostModel(HW["h100_sxm"], calibs["h100_sxm"], "empirical")
    fams = {o.name: cost.explain(o) for o in decode_ops(QWEN, 4, 4096)}
    assert fams["attention"]["family"] == "attn_decode"
    assert fams["qk_norm"]["family"] == "rmsnorm" and fams["qk_norm"]["source"].startswith("measured")
    assert fams["swiglu"]["source"].startswith("proxy:rmsnorm")
    assert fams["embedding"]["source"].startswith("proxy:rmsnorm")
    assert all(d["time_s"] >= d["sol_s"] for d in fams.values())
    assert cost.explain([o for o in prefill_ops(QWEN, 1, 2048) if o.kind == "attention"][0])["family"] \
        == "attn_prefill"
    # a q4_k GEMM with no gemm|q4_k or gemv_q4 curve: plain SOL, and it is counted
    q = Op("qkv_proj", 2.0 * 4096 * 6144, weight_bytes=4096 * 6144 * 0.6, act_bytes=1e4, kind="gemm")
    q.dtype = "q4_k"
    d = cost.explain(q)
    assert d["source"] == "sol_fallback" and d["time_s"] == d["sol_s"]
    assert cost.fallbacks == {"qkv_proj": 1}
    # with a gemv_q4 curve the quantized GEMM uses it (proxy)
    gq = {"op": "gemv_q4", "dtype": "q4_0", "shape": {"N": 4096, "K": 4096}, "us": 20.0,
          "flops": 2.0 * 4096 * 4096, "bytes": 4096 * 4096 * 0.5625}
    cal = fit_calibration(records("h100_sxm") + [gq, dict(gq, us=200.0, bytes=gq["bytes"] * 10)],
                          HW["h100_sxm"])
    assert OpCostModel(HW["h100_sxm"], cal, "empirical").explain(q)["source"].startswith("proxy:gemv_q4")


def test_engine_uses_the_cost_model(calibs):
    h = HW["h100_sxm"]
    sol = OpCostModel(h, mode="sol")
    emp = OpCostModel(h, calibs["h100_sxm"], "empirical")
    t_sol = engine.decode_step_time(QWEN, sol, 16, 1024, engine="vllm")
    t_emp = engine.decode_step_time(QWEN, emp, 16, 1024, engine="vllm")
    assert t_emp > t_sol > 0
    assert engine.prefill_time(QWEN, emp, 1, 2048) > engine.prefill_time(QWEN, sol, 1, 2048)


