def test_sol_hand_values_h100():
    h = HW["h100_sxm"]
    # M=1 GEMV 4096x4096 bf16: memory bound, bytes = (4096 + 4096^2 + 4096) * 2
    fl, nb = bench.gemm_cost(1, 4096, 4096)
    assert fl == 2 * 4096 * 4096 and nb == (4096 + 4096 ** 2 + 4096) * 2
    assert sol_time(fl, nb, h, "bf16") == pytest.approx(nb / 3.35e12)
    # M=4096 square GEMM: compute bound at 989.5 TFLOP/s dense bf16
    fl, nb = bench.gemm_cost(4096, 4096, 4096)
    assert sol_time(fl, nb, h, "bf16") == pytest.approx(2 * 4096 ** 3 / 989.5e12)
    assert fl / nb > h.ridge_point("bf16") > 1.0


def test_dtype_mapping_for_sol():
    h = HW["rtx5090"]
    assert sol_time(1e12, 1.0, h, "f16") == pytest.approx(1e12 / 209.5e12)       # alias
    assert sol_time(1e12, 1.0, h, "q4_k") == pytest.approx(1e12 / 209.5e12)      # dequant -> fp16 math
    assert sol_time(1e12, 1.0, h, "fp8") == pytest.approx(1e12 / 419.0e12)


def test_bench_formulas_match_perfsim_models():
    m = QWEN
    ops = {o.name: o for o in layer_ops(m, 1, 0, 512)}
    # fused qkv GEMM over 512 tokens
    fl, nb = bench.gemm_cost(512, m.hidden, m.q_dim + 2 * m.kv_dim)
    assert fl == ops["qkv_proj"].flops and nb == ops["qkv_proj"].bytes
    # causal prefill attention: same FLOPs; bytes = models' bytes minus the KV-cache append
    fl, nb = bench.attn_cost(1, 512, 512, m.n_heads, m.n_kv_heads, m.head_dim, causal=True)
    a = ops["attention"]
    assert fl == pytest.approx(a.flops)
    assert nb == pytest.approx(a.kv_read_bytes + a.act_bytes)
    # decode attention, L cached + 1 new = kv_len keys
    dec = {o.name: o for o in decode_ops(m, 4, 2047)}["attention"]
    fl, nb = bench.attn_cost(4, 1, 2048, m.n_heads, m.n_kv_heads, m.head_dim, causal=False)
    assert fl == pytest.approx(dec.flops) and nb == pytest.approx(dec.kv_read_bytes + dec.act_bytes)
    # rmsnorm
    fl, nb = bench.rmsnorm_cost(512, m.hidden)
    assert fl == ops["attn_norm"].flops and nb == ops["attn_norm"].bytes


def test_bench_plan_covers_the_requested_grid():
    p = bench.plan(quick=False)
    gemm = [s for s in p if s["op"] == "gemm" and not s["shape"].get("probe")]
    assert {s["shape"]["proj"] for s in gemm} >= {"q", "k", "v", "o", "gate", "up", "down", "lm_head"}
    assert sorted({s["shape"]["M"] for s in gemm}) == list(bench.GEMM_M_FULL)
    dec = [s["shape"] for s in p if s["op"] == "attn_decode" and not s["shape"].get("probe")]
    assert {(d["batch"], d["kv_len"]) for d in dec} == {(b, k) for b in (1, 4, 16, 64)
                                                        for k in (512, 2048, 8192, 32768)}
    assert all(d["n_q_heads"] == 32 and d["n_kv_heads"] == 8 and d["head_dim"] == 128 for d in dec)
    assert sum(1 for s in p if s["shape"].get("probe")) == 4  # one per family


def test_sol_mode_equals_roofline():
    h = HW["h100_sxm"]
    cost = OpCostModel(h, mode="sol")
    for ops in (decode_ops(QWEN, 8, 1000), prefill_ops(QWEN, 2, 300)):
        for o in ops:
            assert cost.time(o) == pytest.approx(op_time(o, h, "bf16").time)
    assert cost.pass_time(decode_ops(QWEN, 8, 1000)) == pytest.approx(
        sum(op_time(o, h, "bf16").total_time for o in decode_ops(QWEN, 8, 1000)))


