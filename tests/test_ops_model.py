@pytest.mark.parametrize("a,b", [("h100_sxm", "rtx5090"), ("rtx5090", "h100_sxm")])
def test_leave_one_gpu_out_projection(calibs, a, b):
    """Same ground-truth efficiencies on both synthetic GPUs -> A's curves on B's spec
    sheet must reproduce B's times (only the probe bias in t0 remains)."""
    cost = OpCostModel.projected(HW[b], calibs[a])
    assert cost.is_projection and "PROJECTION" in cost.describe()
    for r in main_records(b):
        assert predict_record(cost, r) * 1e6 == pytest.approx(r["us"], rel=0.02), r["shape"]
    # the implicit form (what correlate/ calls) is the same model, flagged as a projection
    implicit = OpCostModel(HW[b], calibs[a], mode="empirical")
    assert implicit.is_projection
    with pytest.raises(ValueError):
        OpCostModel(HW[b], calibs[a], mode="empirical", cross_gpu=False)


def test_projection_with_measurement_noise():
    rng = random.Random(0)
    noisy = [dict(r, us=r["us"] * (1 + 0.005 * rng.gauss(0, 1))) for r in records("h100_sxm")]
    cost = OpCostModel.projected(HW["rtx5090"], fit_calibration(noisy, HW["h100_sxm"]))
    errs = [abs(predict_record(cost, r) * 1e6 / r["us"] - 1) for r in main_records("rtx5090")]
    assert max(errs) < 0.02


